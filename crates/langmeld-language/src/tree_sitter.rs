#[derive(Clone, Debug, PartialEq, Eq)]
enum PatternPart {
    Literal(LanguageTokenKind),
    Capture {
        field: String,
        kind: FieldKind,
    },
    Optional(Vec<Self>),
    Choice(Vec<Vec<Self>>),
    Repeat {
        parts: Vec<Self>,
        minimum: usize,
        separator: Option<Vec<Self>>,
    },
}

fn compile_pattern(pattern: &str, construct: &ConstructSpec) -> Option<Vec<PatternPart>> {
    compile_at_depth(pattern, construct, 0)
}

fn compile_at_depth(
    pattern: &str,
    construct: &ConstructSpec,
    repeat_depth: usize,
) -> Option<Vec<PatternPart>> {
    if repeat_depth > 128 {
        return None;
    }
    let mut characters = pattern.char_indices().peekable();
    let mut parts = Vec::new();
    while let Some((offset, character)) = characters.next() {
        if character.is_whitespace() {
            continue;
        }
        match character {
            '\\' => {
                let (_, escaped) = characters.next()?;
                if !matches!(
                    escaped,
                    '[' | ']' | '(' | ')' | '|' | '{' | '}' | '\\' | '@'
                ) {
                    return None;
                }
                parts.push(PatternPart::Literal(LanguageTokenKind::Punctuation(
                    escaped,
                )));
            }
            '[' => {
                let end = matching_delimiter(pattern, offset, '[', ']')?;
                let inner = compile_at_depth(&pattern[offset + 1..end], construct, repeat_depth)?;
                if inner.is_empty() {
                    return None;
                }
                parts.push(PatternPart::Optional(inner));
                while characters
                    .peek()
                    .is_some_and(|(position, _)| *position <= end)
                {
                    characters.next();
                }
            }
            '(' => {
                let end = matching_delimiter(pattern, offset, '(', ')')?;
                let after = pattern[end + 1..].chars().next();
                let body = &pattern[offset + 1..end];
                if matches!(after, Some('*' | '+')) {
                    let mut repeated = compile_at_depth(body, construct, repeat_depth + 1)?;
                    if repeated.is_empty() {
                        return None;
                    }
                    let separator = repeated.last().and_then(|part| {
                        let PatternPart::Optional(optional) = part else {
                            return None;
                        };
                        optional
                            .iter()
                            .all(|part| matches!(part, PatternPart::Literal(_)))
                            .then(|| optional.clone())
                    });
                    if separator.is_some() {
                        repeated.pop();
                    }
                    let minimum = usize::from(after == Some('+'));
                    parts.push(PatternPart::Repeat {
                        parts: repeated,
                        minimum,
                        separator,
                    });
                    let consumed = end + 1 + after.map(char::len_utf8).unwrap_or(0);
                    while characters
                        .peek()
                        .is_some_and(|(position, _)| *position < consumed)
                    {
                        characters.next();
                    }
                } else {
                    let alternatives = split_choice(body)?;
                    let alternatives = alternatives
                        .into_iter()
                        .map(|alternative| compile_at_depth(alternative, construct, repeat_depth))
                        .collect::<Option<Vec<_>>>()?;
                    if alternatives.len() < 2 || alternatives.iter().any(Vec::is_empty) {
                        return None;
                    }
                    parts.push(PatternPart::Choice(alternatives));
                    while characters
                        .peek()
                        .is_some_and(|(position, _)| *position <= end)
                    {
                        characters.next();
                    }
                }
            }
            ')' | ']' | '}' => return None,
            '{' => {
                let Some(relative_end) = pattern[offset + 1..].find('}') else {
                    if pattern[offset + 1..].trim().is_empty() {
                        parts.push(PatternPart::Literal(LanguageTokenKind::Punctuation('{')));
                        continue;
                    }
                    return None;
                };
                let end = relative_end + offset + 1;
                let capture = pattern[offset + 1..end].trim();
                let (root, property) = capture
                    .split_once('.')
                    .map_or((capture, None), |(root, property)| (root, Some(property)));
                let field = construct.fields.iter().find(|field| field.name == root)?;
                let kind = if let Some(property) = property {
                    if repeat_depth != 1 {
                        return None;
                    }
                    let FieldKind::List { item } = &field.kind else {
                        return None;
                    };
                    let FieldKind::Properties { fields, .. } = item.as_ref() else {
                        return None;
                    };
                    fields
                        .iter()
                        .find(|field| field.name == property)?
                        .kind
                        .clone()
                } else {
                    capture_kind(&field.kind, repeat_depth)?.clone()
                };
                parts.push(PatternPart::Capture {
                    field: capture.to_owned(),
                    kind,
                });
                while characters
                    .peek()
                    .is_some_and(|(position, _)| *position <= end)
                {
                    characters.next();
                }
            }
            '-' if characters.peek().is_some_and(|(_, next)| *next == '>') => {
                characters.next();
                parts.push(PatternPart::Literal(LanguageTokenKind::Arrow));
            }
            value
                if value.is_ascii_digit()
                    || (value == '-'
                        && characters
                            .peek()
                            .is_some_and(|(_, next)| next.is_ascii_digit())) =>
            {
                let mut literal = String::from(value);
                let mut decimal_seen = false;
                while let Some((_, next)) = characters.peek().copied() {
                    if next.is_ascii_digit() {
                        literal.push(next);
                        characters.next();
                    } else if next == '.' && !decimal_seen {
                        decimal_seen = true;
                        literal.push(next);
                        characters.next();
                    } else {
                        break;
                    }
                }
                parts.push(PatternPart::Literal(LanguageTokenKind::Number(literal)));
            }
            value if value == '_' || value.is_alphabetic() => {
                let mut literal = String::from(value);
                while let Some((_, next)) = characters.peek().copied() {
                    if next == '_' || next.is_alphanumeric() {
                        literal.push(next);
                        characters.next();
                    } else if next == '-' {
                        let mut lookahead = characters.clone();
                        lookahead.next();
                        if lookahead.peek().is_some_and(|(_, after)| *after == '>') {
                            break;
                        }
                        literal.push(next);
                        characters.next();
                    } else {
                        break;
                    }
                }
                parts.push(PatternPart::Literal(LanguageTokenKind::Identifier(literal)));
            }
            value if value.is_ascii_punctuation() => {
                parts.push(PatternPart::Literal(LanguageTokenKind::Punctuation(value)));
            }
            _ => return None,
        }
    }
    (!parts.is_empty()).then_some(parts)
}

fn capture_kind(kind: &FieldKind, repeat_depth: usize) -> Option<&FieldKind> {
    let mut current = kind;
    for _ in 0..repeat_depth {
        let FieldKind::List { item } = current else {
            return None;
        };
        current = item;
    }
    Some(current)
}

fn matching_delimiter(pattern: &str, opening: usize, left: char, right: char) -> Option<usize> {
    let mut depth = 0_usize;
    let mut escaped = false;
    for (relative, character) in pattern[opening..].char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match character {
            '\\' => escaped = true,
            value if value == left => depth += 1,
            value if value == right => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(opening + relative);
                }
            }
            _ => {}
        }
    }
    None
}

fn split_choice(pattern: &str) -> Option<Vec<&str>> {
    let mut depth = 0_usize;
    let mut escaped = false;
    let mut start = 0;
    let mut alternatives = Vec::new();
    for (offset, character) in pattern.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match character {
            '\\' => escaped = true,
            '(' => depth += 1,
            ')' => depth = depth.checked_sub(1)?,
            '|' if depth == 0 => {
                alternatives.push(pattern[start..offset].trim());
                start = offset + character.len_utf8();
            }
            _ => {}
        }
    }
    if alternatives.is_empty() {
        None
    } else {
        alternatives.push(pattern[start..].trim());
        Some(alternatives)
    }
}

