//! Optional Tree-sitter grammar generation for declarative Langmeld syntax.

use std::collections::{BTreeMap, BTreeSet};

use langmeld_core::{
    BlockSeparator, BlockSeparatorPolicy, ConstructSpec, FieldKind, LanguageSpec, LexicalSpec,
    MapKeyKind, ValidatedLanguageSpec,
};

use crate::{GeneratedArtifacts, LanguageTokenKind, tree_sitter_capture_for_classification};

/// Generate a Tree-sitter grammar and its editor metadata for a language.
///
/// The exporter supports the shared declarative pattern subset. It does not
/// translate custom parser callbacks or host-specific parsing behavior.
///
/// # Errors
/// Returns an explanation if a construct uses a custom parser, a syntax pattern
/// cannot be represented, or generated rule names collide.
pub fn generate_tree_sitter(spec: &ValidatedLanguageSpec) -> Result<GeneratedArtifacts, String> {
    let language = spec.spec();
    let default_lexical = LexicalSpec::default();
    let lexical = language.lexical.as_ref().unwrap_or(&default_lexical);
    if lexical.block_comment.is_some() {
        return Err(
            "Tree-sitter export does not yet represent configured block comments".to_owned(),
        );
    }
    for construct in &language.constructs {
        if let Some(parser) = &construct.custom_parser {
            return Err(format!(
                "construct `{}` uses custom parser `{parser}`; Tree-sitter export requires declarative syntax",
                construct.id
            ));
        }
    }

    let mut names = BTreeMap::new();
    let mut used_names = BTreeSet::new();
    for construct in &language.constructs {
        let name = construct_rule(&construct.id);
        if !used_names.insert(name.clone()) {
            return Err(format!(
                "construct identifiers collide after Tree-sitter rule normalization: `{}`",
                construct.id
            ));
        }
        names.insert(construct.id.as_str(), name);
    }
    let reserved = [
        "source_file",
        "lm_separator",
        "lm_semicolon",
        "lm_identifier",
        "lm_number",
        "lm_string",
        "comment",
    ];
    if let Some((id, name)) = names
        .iter()
        .find(|(_, name)| reserved.contains(&name.as_str()))
    {
        return Err(format!(
            "construct `{id}` maps to reserved Tree-sitter rule `{name}`"
        ));
    }

    let root = names
        .get(language.root.as_str())
        .ok_or_else(|| format!("root construct `{}` is missing", language.root))?;
    let mut rules = vec![format!(
        "source_file: $ => seq(repeat($.lm_newline), $.{root}, repeat($.lm_separator))"
    )];
    let mut conflicts = Vec::new();
    let mut type_rules = TypeRuleBuilder::default();
    for construct in &language.constructs {
        if language.schema_version >= 2
            && construct
                .block
                .as_ref()
                .is_some_and(|block| block_literal_token_count(&block.close) > 1)
        {
            conflicts.push(format!("[$.{}]", construct_rule(&construct.id)));
        }
        rules.push(construct_rule_definition(
            construct,
            language,
            &names,
            &mut type_rules,
        )?);
    }
    rules.extend(type_rules.definitions.iter().cloned());
    rules.extend([
        "lm_newline: _ => /\\r?\\n/".to_owned(),
        "lm_separator: $ => choice($.lm_newline, $.lm_semicolon)".to_owned(),
        "lm_semicolon: _ => \";\"".to_owned(),
        "lm_identifier: _ => /[_\\p{L}][_\\p{L}\\p{N}-]*/".to_owned(),
        "lm_number: _ => /-?[0-9]+(?:\\.[0-9]+)?/".to_owned(),
        r#"lm_string: $ => token(seq("\"", repeat(choice(/[^"\\\r\n]/, /\\[nrt"\\]/)), "\""))"#
            .to_owned(),
    ]);
    if let Some(line_comment) = &lexical.line_comment {
        rules.push(format!(
            "comment: $ => token(seq({}, /[^\\r\\n]*/))",
            js_string(line_comment)
        ));
    }

    let grammar_name = safe_identifier(&language.name);
    let package_name = format!("tree-sitter-{}", safe_slug(&language.name));
    let grammar = format!(
        "// Generated by Langmeld. Edit the language definition, then regenerate.\n\
         module.exports = grammar({{\n  name: {},\n  word: $ => $.lm_identifier,\n\
         {}\
         extras: $ => [/[ \\t\\r]/{}],\n  rules: {{\n    {}\n  }},\n}});\n",
        js_string(&grammar_name),
        if conflicts.is_empty() {
            String::new()
        } else {
            format!("  conflicts: $ => [{}],\n", conflicts.join(", "))
        },
        lexical
            .line_comment
            .as_ref()
            .map_or_else(String::new, |_| ", $.comment".to_owned()),
        rules.join(",\n    "),
    );
    let enum_rule_names = type_rules
        .entries
        .iter()
        .filter_map(|(kind, name)| {
            matches!(kind, FieldKind::Enum { .. } | FieldKind::NamedEnum { .. })
                .then_some(name.as_str())
        })
        .collect::<Vec<_>>();
    let highlights = highlighting_query(language, &type_rules.used_builtin_nodes, &enum_rule_names);
    let tree_sitter_json = json_file(&serde_json::json!({
        "grammars": [{
            "name": grammar_name,
            "scope": format!("source.{grammar_name}"),
            "path": ".",
            "highlights": "queries/highlights.scm"
        }],
        "metadata": {
            "version": "0.1.0",
            "description": format!("Generated Tree-sitter grammar for {} {}", language.name, language.version),
            "authors": [{"name": "Langmeld generated"}]
        }
    }))?;
    let package_json = json_file(&serde_json::json!({
        "name": package_name,
        "version": "0.1.0",
        "description": format!("Generated Tree-sitter grammar for {} {}", language.name, language.version),
        "keywords": ["tree-sitter", "grammar", safe_slug(&language.name)],
    }))?;

    let mut artifacts = GeneratedArtifacts::new();
    artifacts.insert("tree-sitter/grammar.js".to_owned(), grammar);
    artifacts.insert("tree-sitter/tree-sitter.json".to_owned(), tree_sitter_json);
    artifacts.insert("tree-sitter/package.json".to_owned(), package_json);
    artifacts.insert("tree-sitter/queries/highlights.scm".to_owned(), highlights);
    artifacts.insert(
        "tree-sitter/README.md".to_owned(),
        tree_sitter_readme(&language.name, lexical.line_comment.as_deref()),
    );
    Ok(artifacts)
}

fn json_file(value: &serde_json::Value) -> Result<String, String> {
    serde_json::to_string_pretty(value)
        .map(|json| json + "\n")
        .map_err(|error| format!("cannot serialize Tree-sitter metadata: {error}"))
}

fn construct_rule(id: &str) -> String {
    let suffix = id
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect::<String>();
    format!("lm_construct_{suffix}")
}

fn construct_rule_definition(
    construct: &ConstructSpec,
    language: &LanguageSpec,
    names: &BTreeMap<&str, String>,
    type_rules: &mut TypeRuleBuilder,
) -> Result<String, String> {
    let mut alternatives = Vec::with_capacity(construct.syntax.len());
    for pattern in &construct.syntax {
        let parts = compile_pattern(pattern, construct).ok_or_else(|| {
            format!(
                "construct `{}` has unsupported Tree-sitter syntax pattern `{pattern}`",
                construct.id
            )
        })?;
        let mut expression = pattern_expression(&parts, construct, type_rules)?;
        if let Some(block) = &construct.block {
            if language.schema_version == 1 {
                if !matches!(
                    parts.last(),
                    Some(PatternPart::Literal(LanguageTokenKind::Punctuation('{')))
                ) {
                    return Err(format!(
                        "block construct `{}` pattern `{pattern}` must end with `{{` for Tree-sitter export",
                        construct.id
                    ));
                }
            } else {
                let open = literal_token_sequence_expression(&block.open, &construct.id, "opener")?;
                expression = format!("seq({expression}, {open})");
            }
            let mut children = Vec::new();
            let mut seen = BTreeSet::new();
            for allowed in &block.allowed {
                if let Some(name) = names.get(allowed.as_str()) {
                    if seen.insert(name.clone()) {
                        children.push(format!("$.{name}"));
                    }
                } else if language
                    .categories
                    .iter()
                    .any(|category| category.id == *allowed)
                {
                    for candidate in language
                        .constructs
                        .iter()
                        .filter(|candidate| candidate.implements.contains(allowed))
                    {
                        let name = construct_rule(&candidate.id);
                        if seen.insert(name.clone()) {
                            children.push(format!("$.{name}"));
                        }
                    }
                } else {
                    return Err(format!(
                        "block `{}` references unknown construct or category `{allowed}`",
                        construct.id
                    ));
                }
            }
            let body = if children.is_empty() {
                if block.separators.is_empty() {
                    "".to_owned()
                } else {
                    let separator = block_separator_expression(block, &construct.id)?;
                    if block_has_newline_separator(block) {
                        format!("repeat({separator})")
                    } else {
                        format!(
                            "seq(repeat($.lm_newline), repeat({separator}), repeat($.lm_newline))"
                        )
                    }
                }
            } else if block.separators.is_empty() {
                let child = choice_expr(children);
                format!("repeat({child})")
            } else {
                let child = choice_expr(children);
                let separator = block_separator_expression(block, &construct.id)?;
                let layout_separator = block_has_newline_separator(block);
                let repeated_separator = format!("repeat({separator})");
                let (empty_body, leading, trailing) = if layout_separator {
                    (
                        repeated_separator.clone(),
                        repeated_separator.clone(),
                        repeated_separator,
                    )
                } else {
                    let layout = |inner: &str| {
                        format!("seq(repeat($.lm_newline), {inner}, repeat($.lm_newline))")
                    };
                    (
                        layout(&format!("repeat({separator})")),
                        layout(&format!("repeat({separator})")),
                        layout(&format!("repeat({separator})")),
                    )
                };
                let between = match block.separator_policy {
                    BlockSeparatorPolicy::Optional => format!("repeat({separator})"),
                    BlockSeparatorPolicy::Required => format!("repeat1({separator})"),
                };
                let between = if layout_separator {
                    between
                } else {
                    format!("seq(repeat($.lm_newline), {between}, repeat($.lm_newline))")
                };
                format!(
                    "choice({empty_body}, seq({leading}, {child}, repeat(seq({between}, {child})), {trailing}))"
                )
            };
            if body.is_empty() {
                let close =
                    literal_token_sequence_expression(&block.close, &construct.id, "closer")?;
                expression = format!("seq({expression}, {close})");
            } else {
                let close =
                    literal_token_sequence_expression(&block.close, &construct.id, "closer")?;
                expression = format!("seq({expression}, {body}, {close})");
            }
        }
        alternatives.push(expression);
    }
    if alternatives.is_empty() {
        return Err(format!(
            "construct `{}` has no syntax patterns for Tree-sitter export",
            construct.id
        ));
    }
    Ok(format!(
        "{}: $ => {}",
        construct_rule(&construct.id),
        choice_expr(alternatives)
    ))
}

fn block_separator_expression(
    block: &langmeld_core::BlockSpec,
    construct: &str,
) -> Result<String, String> {
    if block.uses_default_layout() {
        return Ok("$.lm_separator".to_owned());
    }
    let separators = block
        .separators
        .iter()
        .map(|separator| match separator {
            BlockSeparator::Newline => Ok("$.lm_newline".to_owned()),
            BlockSeparator::Literal(value) if is_single_punctuation(value, ';') => {
                Ok("$.lm_semicolon".to_owned())
            }
            BlockSeparator::Literal(value) => {
                literal_token_sequence_expression(value, construct, "separator")
            }
        })
        .collect::<Result<Vec<_>, String>>()?;
    match separators.len() {
        0 => Err("block has no configured separators".to_owned()),
        1 => Ok(separators.into_iter().next().unwrap_or_default()),
        _ => Ok(choice_expr(separators)),
    }
}

fn block_has_newline_separator(block: &langmeld_core::BlockSpec) -> bool {
    block.uses_default_layout()
        || block
            .separators
            .iter()
            .any(|separator| matches!(separator, BlockSeparator::Newline))
}

fn is_single_punctuation(value: &str, expected: char) -> bool {
    let source = langmeld_core::SourceFile::new("<block-separator>", value);
    let (tokens, diagnostics, limited) = crate::lexing::lex(&source, 64);
    if limited || !diagnostics.is_empty() {
        return false;
    }
    let mut tokens = tokens
        .into_iter()
        .filter(|token| !matches!(token.kind, LanguageTokenKind::End));
    matches!(
        (tokens.next(), tokens.next()),
        (Some(token), None) if token.kind == LanguageTokenKind::Punctuation(expected)
    )
}

fn block_literal_token_count(value: &str) -> usize {
    let source = langmeld_core::SourceFile::new("<block-literal>", value);
    let (tokens, diagnostics, limited) = crate::lexing::lex(&source, 64);
    if limited || !diagnostics.is_empty() {
        return 0;
    }
    tokens
        .iter()
        .filter(|token| !matches!(token.kind, LanguageTokenKind::End))
        .count()
}

fn literal_token_sequence_expression(
    value: &str,
    construct: &str,
    role: &str,
) -> Result<String, String> {
    let source = langmeld_core::SourceFile::new("<block-literal>", value);
    let (tokens, diagnostics, limited) = crate::lexing::lex(&source, 64);
    if limited || !diagnostics.is_empty() {
        return Err(format!(
            "block {role} `{value}` in construct `{construct}` cannot be represented by Tree-sitter"
        ));
    }
    let mut expressions = Vec::new();
    for token in tokens {
        if matches!(token.kind, LanguageTokenKind::End) {
            continue;
        }
        let lexeme = source
            .text
            .get(token.span.start..token.span.end)
            .ok_or_else(|| {
                format!(
                    "block {role} `{value}` in construct `{construct}` has an invalid token span"
                )
            })?;
        let expression = match token.kind {
            LanguageTokenKind::Identifier(_) | LanguageTokenKind::Number(_) => js_string(lexeme),
            LanguageTokenKind::Punctuation(_) => js_string(lexeme),
            LanguageTokenKind::Arrow => js_string("->"),
            LanguageTokenKind::Text(_) => {
                return Err(format!(
                    "block {role} `{value}` in construct `{construct}` contains a string token whose accepted escape spellings cannot be exported exactly"
                ));
            }
            LanguageTokenKind::Unknown(_)
            | LanguageTokenKind::Opaque
            | LanguageTokenKind::Comment
            | LanguageTokenKind::Newline => {
                return Err(format!(
                    "block {role} `{value}` in construct `{construct}` contains a token that cannot be represented by Tree-sitter"
                ));
            }
            LanguageTokenKind::End => unreachable!("end tokens were skipped"),
        };
        expressions.push(expression);
    }
    if expressions.is_empty() {
        return Err(format!(
            "block {role} `{value}` in construct `{construct}` has no source tokens"
        ));
    }
    let mut sequence = Vec::with_capacity(expressions.len() * 2 - 1);
    for (index, expression) in expressions.into_iter().enumerate() {
        if index > 0 {
            sequence.push("repeat($.lm_newline)".to_owned());
        }
        sequence.push(expression);
    }
    Ok(seq_expr(sequence))
}

fn pattern_expression(
    parts: &[PatternPart],
    construct: &ConstructSpec,
    type_rules: &mut TypeRuleBuilder,
) -> Result<String, String> {
    let expressions = parts
        .iter()
        .map(|part| pattern_part_expression(part, construct, type_rules))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(seq_expr(expressions))
}

fn pattern_part_expression(
    part: &PatternPart,
    construct: &ConstructSpec,
    type_rules: &mut TypeRuleBuilder,
) -> Result<String, String> {
    match part {
        PatternPart::Literal(kind) => match kind {
            LanguageTokenKind::Identifier(value) | LanguageTokenKind::Number(value) => {
                Ok(js_string(value))
            }
            LanguageTokenKind::Punctuation(character) => Ok(js_string(&character.to_string())),
            LanguageTokenKind::Arrow => Ok(js_string("->")),
            LanguageTokenKind::Text(value) => Ok(js_string(&format!("\"{value}\""))),
            LanguageTokenKind::Unknown(character) => Err(format!(
                "literal `{character}` in construct `{}` cannot be exported to Tree-sitter",
                construct.id
            )),
            LanguageTokenKind::Comment
            | LanguageTokenKind::Newline
            | LanguageTokenKind::Opaque
            | LanguageTokenKind::End => Err(format!(
                "non-source literal in construct `{}` cannot be exported to Tree-sitter",
                construct.id
            )),
        },
        PatternPart::Capture { field, kind } => {
            let expression = type_rules.expression(kind)?;
            Ok(format!(
                "field({}, {expression})",
                js_string(&tree_sitter_field_name(field))
            ))
        }
        PatternPart::Optional(inner) => Ok(format!(
            "optional({})",
            pattern_expression(inner, construct, type_rules)?
        )),
        PatternPart::Choice(alternatives) => alternatives
            .iter()
            .map(|alternative| pattern_expression(alternative, construct, type_rules))
            .collect::<Result<Vec<_>, _>>()
            .map(choice_expr),
        PatternPart::Repeat {
            parts,
            minimum,
            separator,
        } => {
            let expression = pattern_expression(parts, construct, type_rules)?;
            if let Some(separator) = separator {
                let separator = pattern_expression(separator, construct, type_rules)?;
                let separated = format!(
                    "seq({expression}, repeat(seq({separator}, {expression})), optional({separator}))"
                );
                if *minimum == 0 {
                    Ok(format!("optional({separated})"))
                } else {
                    Ok(separated)
                }
            } else if *minimum == 0 {
                Ok(format!("repeat({expression})"))
            } else {
                Ok(format!("repeat1({expression})"))
            }
        }
    }
}

#[derive(Default)]
struct TypeRuleBuilder {
    entries: Vec<(FieldKind, String)>,
    definitions: Vec<String>,
    used_builtin_nodes: BTreeSet<&'static str>,
}

impl TypeRuleBuilder {
    fn expression(&mut self, kind: &FieldKind) -> Result<String, String> {
        match kind {
            FieldKind::Identifier | FieldKind::Reference { .. } => {
                self.used_builtin_nodes.insert("lm_identifier");
                Ok("$.lm_identifier".to_owned())
            }
            FieldKind::Number => {
                self.used_builtin_nodes.insert("lm_number");
                Ok("$.lm_number".to_owned())
            }
            FieldKind::Text => {
                self.used_builtin_nodes.insert("lm_string");
                Ok("$.lm_string".to_owned())
            }
            FieldKind::Enum { .. }
            | FieldKind::NamedEnum { .. }
            | FieldKind::List { .. }
            | FieldKind::Properties { .. }
            | FieldKind::Map { .. } => self.named_expression(kind),
            FieldKind::Expression { grammar, .. } => Err(format!(
                "Tree-sitter export does not yet represent expression field grammar `{grammar}`"
            )),
        }
    }

    fn named_expression(&mut self, kind: &FieldKind) -> Result<String, String> {
        if let Some((_, name)) = self.entries.iter().find(|(existing, _)| existing == kind) {
            return Ok(format!("$.{name}"));
        }
        let name = format!("lm_type_{}", self.entries.len());
        self.entries.push((kind.clone(), name.clone()));
        let expression = match kind {
            FieldKind::Enum { values } | FieldKind::NamedEnum { values, .. } => {
                choice_expr(values.iter().map(|value| js_string(value)).collect())
            }
            FieldKind::List { item } => {
                let item = self.expression(item)?;
                let newlines = "repeat($.lm_newline)";
                let items = format!(
                    "seq({newlines}, {item}, repeat(seq({newlines}, \",\", {newlines}, {item})), {newlines}, optional(seq(\",\", {newlines})))"
                );
                format!("seq(\"[\", choice({newlines}, {items}), \"]\")")
            }
            FieldKind::Properties { fields, .. } => {
                let mut properties = Vec::with_capacity(fields.len());
                for field in fields {
                    let value = self.expression(&field.kind)?;
                    properties.push(format!(
                        "field({}, seq({}, \":\", {value}))",
                        js_string(&tree_sitter_field_name(&field.name)),
                        js_string(&tree_sitter_field_name(&field.name))
                    ));
                }
                let separator = "choice(\",\", \";\", $.lm_newline)";
                let separators = format!("repeat({separator})");
                if properties.is_empty() {
                    format!("seq(\"{{\", {separators}, \"}}\")")
                } else {
                    let properties = choice_expr(properties);
                    format!(
                        "seq(\"{{\", choice({separators}, seq({separators}, {properties}, repeat(seq(repeat1({separator}), {properties})), {separators})), \"}}\")"
                    )
                }
            }
            FieldKind::Map { key, value } => {
                let key = match key {
                    MapKeyKind::Identifier => {
                        self.used_builtin_nodes.insert("lm_identifier");
                        "$.lm_identifier"
                    }
                    MapKeyKind::Text => {
                        self.used_builtin_nodes.insert("lm_string");
                        "$.lm_string"
                    }
                };
                let value = self.expression(value)?;
                let newlines = "repeat($.lm_newline)";
                let separator = "choice(\",\", \";\")";
                let entry = format!("field(\"key\", {key}), \":\", field(\"value\", {value})");
                format!(
                    "seq(\"{{\", choice({newlines}, seq({newlines}, {entry}, repeat(seq({newlines}, {separator}, {newlines}, {entry})), {newlines}, optional(seq({separator}, {newlines})))), \"}}\")"
                )
            }
            FieldKind::Identifier
            | FieldKind::Number
            | FieldKind::Text
            | FieldKind::Reference { .. }
            | FieldKind::Expression { .. } => unreachable!("primitive types are not named"),
        };
        self.definitions.push(format!("{name}: $ => {expression}"));
        Ok(format!("$.{name}"))
    }
}

fn choice_expr(mut expressions: Vec<String>) -> String {
    match expressions.len() {
        0 => "choice()".to_owned(),
        1 => expressions.pop().unwrap_or_default(),
        _ => format!("choice({})", expressions.join(", ")),
    }
}

fn tree_sitter_field_name(name: &str) -> String {
    let mut bytes = name.bytes();
    let valid_identifier = bytes
        .next()
        .is_some_and(|byte| byte == b'_' || byte.is_ascii_alphabetic())
        && bytes.all(|byte| byte == b'_' || byte.is_ascii_alphanumeric())
        && !name.starts_with("lmf_enc_");
    if valid_identifier {
        return name.to_owned();
    }

    let mut encoded = String::with_capacity("lmf_enc_".len() + name.len() * 2);
    encoded.push_str("lmf_enc_");
    for byte in name.bytes() {
        encoded.push(char::from(b"0123456789abcdef"[(byte >> 4) as usize]));
        encoded.push(char::from(b"0123456789abcdef"[(byte & 0x0f) as usize]));
    }
    encoded
}

fn seq_expr(mut expressions: Vec<String>) -> String {
    match expressions.len() {
        0 => "seq()".to_owned(),
        1 => expressions.pop().unwrap_or_default(),
        _ => format!("seq({})", expressions.join(", ")),
    }
}

fn js_string(value: &str) -> String {
    serde_json::to_string(value).unwrap_or_else(|_| "\"\"".to_owned())
}

fn safe_slug(value: &str) -> String {
    let mut output = String::new();
    let mut previous_dash = false;
    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            output.push(character.to_ascii_lowercase());
            previous_dash = false;
        } else if !previous_dash && !output.is_empty() {
            output.push('-');
            previous_dash = true;
        }
    }
    let slug = output.trim_end_matches('-');
    if slug.is_empty() {
        "language".to_owned()
    } else {
        slug.to_owned()
    }
}

fn safe_identifier(value: &str) -> String {
    let slug = safe_slug(value).replace('-', "_");
    if slug.as_bytes()[0].is_ascii_digit() {
        format!("language_{slug}")
    } else {
        slug
    }
}

fn highlighting_query(
    language: &LanguageSpec,
    used_builtin_nodes: &BTreeSet<&str>,
    enum_rule_names: &[&str],
) -> String {
    let mut keywords = BTreeSet::new();
    let mut operators = BTreeSet::new();
    for construct in &language.constructs {
        for pattern in &construct.syntax {
            if let Some(parts) = compile_pattern(pattern, construct) {
                collect_query_tokens(&parts, &mut keywords, &mut operators);
            }
        }
    }
    let default_lexical = LexicalSpec::default();
    let lexical = language.lexical.as_ref().unwrap_or(&default_lexical);
    let mut query = if lexical.line_comment.is_some() {
        tree_sitter_capture_for_classification("comment")
            .map(|capture| format!("(comment) @{capture}\n"))
            .unwrap_or_default()
    } else {
        String::new()
    };
    for (node, classification) in [
        ("lm_identifier", "identifier"),
        ("lm_number", "number"),
        ("lm_string", "string"),
    ] {
        if used_builtin_nodes.contains(node)
            && let Some(capture) = tree_sitter_capture_for_classification(classification)
        {
            query.push_str(&format!("({node}) @{capture}\n"));
        }
    }
    for keyword in keywords {
        if let Some(capture) = tree_sitter_capture_for_classification("keyword") {
            query.push_str(&format!("{} @{capture}\n", js_string(&keyword)));
        }
    }
    for operator in operators {
        if let Some(capture) = tree_sitter_capture_for_classification("operator") {
            query.push_str(&format!("{} @{capture}\n", js_string(&operator)));
        }
    }
    for rule in enum_rule_names {
        if let Some(capture) = tree_sitter_capture_for_classification("enumMember") {
            query.push_str(&format!("({rule}) @{capture}\n"));
        }
    }
    query
}

fn collect_query_tokens(
    parts: &[PatternPart],
    keywords: &mut BTreeSet<String>,
    operators: &mut BTreeSet<String>,
) {
    for part in parts {
        match part {
            PatternPart::Literal(LanguageTokenKind::Identifier(value)) => {
                keywords.insert(value.clone());
            }
            PatternPart::Literal(LanguageTokenKind::Punctuation(value)) => {
                let punctuation = value.to_string();
                if !"{}[](),:;".contains(punctuation.as_str()) {
                    operators.insert(punctuation);
                }
            }
            PatternPart::Literal(LanguageTokenKind::Arrow) => {
                operators.insert("->".to_owned());
            }
            PatternPart::Optional(inner) => {
                collect_query_tokens(inner, keywords, operators);
            }
            PatternPart::Repeat {
                parts, separator, ..
            } => {
                collect_query_tokens(parts, keywords, operators);
                if let Some(separator) = separator {
                    collect_query_tokens(separator, keywords, operators);
                }
            }
            PatternPart::Choice(alternatives) => {
                for alternative in alternatives {
                    collect_query_tokens(alternative, keywords, operators);
                }
            }
            PatternPart::Literal(
                LanguageTokenKind::Number(_)
                | LanguageTokenKind::Text(_)
                | LanguageTokenKind::Comment
                | LanguageTokenKind::Newline
                | LanguageTokenKind::Opaque
                | LanguageTokenKind::End
                | LanguageTokenKind::Unknown(_),
            )
            | PatternPart::Capture { .. } => {}
        }
    }
}

